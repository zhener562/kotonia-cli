async fn run_mail_tool(
    name: &str,
    input: &serde_json::Value,
    connector: Option<&str>,
    allowed: Option<&[String]>,
) -> Result<String, String> {
    use crate::connectors::{mail, Registry};
    let registry = Registry::load()?;
    if let (Some(id), Some(allowed)) = (connector, allowed) {
        if !allowed.iter().any(|a| a == id) {
            return Err(format!(
                "`{id}` is not allowed in this folder (allowed: {})",
                allowed.join(", ")
            ));
        }
    }
    let record = match (connector, allowed) {
        (Some(id), _) => registry.connectors.get(id).cloned(),
        (None, Some(allowed)) => allowed
            .iter()
            .find_map(|id| registry.connectors.get(id))
            .cloned(),
        (None, None) => registry.first_mail().cloned(),
    }
    .ok_or_else(|| {
        "no mail account is connected — call request_connector with connector \"gmail\" \
         (or \"icloud\" / \"imap\") if you need one"
            .to_string()
    })?;
    let secret = crate::vault::Vault::resolve()?
        .get(&record.id)?
        .ok_or_else(|| {
            format!(
                "the password for `{}` is missing; ask the user to reconnect",
                record.id
            )
        })?;
    let offset = *chrono::Local::now().offset();
    if name == "mail_search" {
        let query = input.get("query").and_then(|v| v.as_str()).unwrap_or("");
        let limit = input
            .get("limit")
            .and_then(|v| v.as_u64())
            .unwrap_or(20)
            .clamp(1, 50) as usize;
        let (mailbox, items) = mail::search(&record, &secret, query, limit).await?;
        return Ok(format!(
            "(searched mailbox \"{mailbox}\" for {query:?}: {} result(s); read with mail_read {{uid, mailbox: \"{mailbox}\"}})\n{}",
            items.len(),
            mail::format_summaries(&items, offset)
        ));
    }
    if name == "mail_recent" {
        let window = if input.get("new").and_then(|v| v.as_bool()).unwrap_or(false) {
            mail::Window::New
        } else {
            mail::Window::SinceDays(input.get("days").and_then(|v| v.as_i64()).unwrap_or(2))
        };
        let limit = input
            .get("limit")
            .and_then(|v| v.as_u64())
            .unwrap_or(20)
            .clamp(1, 50) as usize;
        let items = mail::recent(&record, &secret, window, limit).await?;
        Ok(mail::format_summaries(&items, offset))
    } else {
        let uid = input
            .get("uid")
            .and_then(|v| v.as_u64())
            .ok_or("mail_read needs `uid`")? as u32;
        let max = input
            .get("max_chars")
            .and_then(|v| v.as_u64())
            .unwrap_or(12_000) as usize;
        let mailbox = mail::Mailbox::parse(input.get("mailbox").and_then(|v| v.as_str()));
        let text = mail::read(&record, &secret, uid, offset, false, mailbox).await?;
        let text = match text.char_indices().nth(max) {
            Some((i, _)) => format!("{}\n… (cut at {max} characters)", &text[..i]),
            None => text,
        };
        Ok(mail::wrap_untrusted(&text))
    }
}

